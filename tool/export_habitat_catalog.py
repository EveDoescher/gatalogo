"""Export the API catalog to Dart. Run after catalog changes; --check detects drift."""

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_shop(api: Path):
    tree = ast.parse((api / "app/services/habitat_service.py").read_text(encoding="utf-8"))
    return next(ast.literal_eval(node.value) for node in tree.body
                if isinstance(node, ast.AnnAssign) and node.target.id == "SHOP")


def export(shop):
    lines = ["// Generated by tool/export_habitat_catalog.py from the API catalog.",
             "part of 'habitat_service.dart';", "", "const _offlineShop = ["]
    keys = {"max_owned": "maxOwned"}
    for sku, definition in shop.items():
        lines.append("  HabitatShopItem(")
        for key, value in {"sku": sku, **definition}.items():
            lines.append(f"    {keys.get(key, key)}: {json.dumps(value, ensure_ascii=False)},")
        lines.append("  ),")
    return "\n".join(lines + ["];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--api", type=Path, default=ROOT.parent / "gatalogo-ai-api")
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    output = ROOT / "lib/services/habitat_catalog.g.dart"
    content = export(read_shop(options.api))
    if options.check:
        if output.read_text(encoding="utf-8") != content:
            raise SystemExit("Habitat fallback differs from the API. Run export_habitat_catalog.py.")
    else:
        output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
